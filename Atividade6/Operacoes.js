let num1 = prompt("Digite o primeiro número: ");
let num2 = prompt("Digite o segundo número: ");

let soma = parseFloat(num1) + parseFloat(num2);
alert("Soma: "+soma);

let subtracao = parseFloat(num1) - parseFloat(num2);
alert("Subtração do primeiro pelo segundo: "+subtracao);

let produto = parseFloat(num1) * parseFloat(num2);
alert("Produto: "+produto);

let divisao = parseFloat(num1) / parseFloat(num2);
alert("Divisão do primeiro pelo segundo: "+divisao);

let resto = parseFloat(num1) % parseFloat(num2);
alert("Resto da divisão do primeiro pelo segundo: "+resto);